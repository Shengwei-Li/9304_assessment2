function export_slx_figs()
%EXPORT_SLX_FIGS  Export numbered screenshots of hydrofoil_sim for simulink_guide.html.
%   Temporary numbered labels are added next to the blocks, the diagrams are
%   printed to ./figs/guide_*.png, and the model is closed WITHOUT saving, so
%   the .slx file itself is not changed.

mdl  = 'hydrofoil_sim';
here = fileparts(mfilename('fullpath'));
if bdIsLoaded(mdl), close_system(mdl, 0); end
load_system(fullfile(here, [mdl '.slx']));
evalin('base', 'hydrofoil_sim_init; ctrl_ext = 0;');                % default: controller inside the model
set_param(mdl, 'SimulationCommand', 'update');                  % so the variant icon shows "Onboard"

% {subsystem path ('' = top level), output file, {block name, label; ...}}
jobs = { ...
 '', 'guide_top', { ...
    'Trim u0','1'; 'Foil command','2'; 'Height reference','3'; 'Controller','4'; 'Sum cmd','5'; ...
    'Actuators','6'; 'Nonlinear boat','7'; 'Waves','8'; 'Sensor','9'; 'log y_meas','10'; ...
    'Goto delta','T1'; 'Goto x','T2'; 'Goto w','T3'; 'Goto y_meas','T4'; 'From y_meas','T4'; ...
    'From delta ctrl','T1'; 'From delta','T1'; 'Trim u0 lin','1'; 'Sum dev','11'; 'From w','T3'; ...
    'Mux lin','12'; 'Linear model','13'; 'From x','T2'; 'Scope states','14'; 'log x_lin','15'; ...
    'Encoder','18'; ...
    'From delta log','T1'; 'log delta','16'; 'From x log','T2'; 'log x_nl','17'; ...
    'Goto r','T5'; 'Goto xh','T6'; 'Goto st','T7'; 'Goto u_fb','T8'; ...
    'From xh log','T6'; 'log xhat','20'; 'From st log','T7'; 'log link','21'; ...
    'From tel x_nl','T2'; 'From tel delta','T1'; 'From tel y_meas','T4'; 'From tel r','T5'; ...
    'From tel xh','T6'; 'From tel link','T7'; 'From tel u_fb','T8'; 'Telemetry','19'}; ...
 '/Actuators', 'guide_actuators', { ...
    'u_cmd','1'; 'Position limit','2'; 'Servo error','3'; '1 over tau','4'; 'Rate limit','5'; ...
    'Foil angle','6'; 'act_on','7'; 'Ideal or real','8'; 'delta','9'}; ...
 '/Nonlinear boat', 'guide_boat', { ...
    'delta','1'; 'w','2'; 'Boat dynamics','3'; 'States','4'; 'x','5'}; ...
 '/Waves', 'guide_waves', { ...
    'Time','1'; 'Wave field','2'; 'wave_on w','3'; 'wave_on zeta','4'; 'to vector','5'; ...
    'w','6'; 'zeta_s','7'}; ...
 '/Sensor', 'guide_sensor', { ...
    'x','1'; 'Demux','2'; 'sin','3'; 'ls','4'; 'zeta_s','5'; 'Height noise','6'; ...
    'noise_on h','7'; 'Ultrasonic height','8'; 'Angle noise','9'; 'noise_on th','10'; ...
    'AHRS pitch angle','11'; 'Gyro noise','12'; 'noise_on q','13'; 'Pitch-rate gyro','14'; ...
    'Mux','15'; 'y_meas','16'}; ...
 '/Controller', 'guide_controller', { ...
    'y_meas','1'; 'delta','2'; 'r','3'; 'Onboard','4'; 'External (TCP)','5'; ...
    'u_fb','6'; 'xh','7'; 'link','8'}; ...
 '/Controller/Onboard', 'guide_ctrl_onboard', { ...
    'y_meas','1'; 'delta','2'; 'r','3'; 'Digital controller','4'; 'ctrl_on','5'; ...
    'to vector','6'; 'u_fb','7'; 'xh','8'; 'no link','9'; 'link','10'}; ...
 '/Controller/External (TCP)', 'guide_ctrl_external', { ...
    'y_meas','1'; 'delta','2'; 'r','3'; 'TCP link','4'; 'ctrl_on','5'; ...
    'to vector','6'; 'u_fb','7'; 'xh','8'; 'link','9'}; ...
 '/Telemetry', 'guide_telemetry', { ...
    'Time','1'; 'x_nl','2'; 'delta','3'; 'y_meas','4'; 'r','5'; 'xh','6'; 'link','7'; 'u_fb','8'; ...
    'Send','9'}};

% labels that would collide with something else are moved to the left of / below the block
shift = containers.Map();
shift('|Trim u0 lin')    = [-30, 4];
shift('|From w')         = [-34, 4];
shift('|From delta log') = [-34, 4];
shift('|From x log')     = [-34, 4];
shift('/Sensor|sin')     = [10, 24];
shift('/Actuators|act_on') = [-30, 2];
shift('/Nonlinear boat|w') = [-4, 18];
shift('|Height reference') = [-30, 4];
shift('|From delta ctrl') = [-30, 2];
shift('|Encoder') = [34, -14];
shift('|Goto r') = [-30, 4];
shift('|Goto u_fb') = [56, 4];
shift('|Goto xh') = [56, 4];
shift('|Goto st') = [56, 4];
shift('|From xh log') = [-34, 4];
shift('|From st log') = [-34, 4];
for t_ = {'x_nl', 'delta', 'y_meas', 'r', 'xh', 'link', 'u_fb'}
    shift(['|From tel ' t_{1}]) = [-34, 4];
    shift(['/Telemetry|' t_{1}]) = [-26, 0];
end
shift('/Telemetry|Time') = [-26, 2];
shift('/Waves|wave_on zeta') = [-32, 4];

for j = 1:size(jobs, 1)
    sys = [mdl jobs{j,1}];
    marks = jobs{j,3};
    for k = 1:size(marks, 1)
        pos = get_param([sys '/' marks{k,1}], 'Position');     % [left top right bottom]
        isTag = marks{k,2}(1) == 'T';
        a = Simulink.Annotation(sys, marks{k,2});
        off = [-6, -22];                                       % default: above the top-left corner
        key = [jobs{j,1} '|' marks{k,1}];
        if isKey(shift, key), off = shift(key); end
        a.Position        = [pos(1) + off(1), pos(2) + off(2)];
        a.FontSize        = 11;
        a.FontWeight      = 'bold';
        a.ForegroundColor = 'white';
        if isTag, a.BackgroundColor = 'blue'; else, a.BackgroundColor = 'red'; end
    end
    print(['-s' sys], '-dpng', '-r150', fullfile(here, 'figs', [jobs{j,2} '.png']));
end
close_system(mdl, 0);                                           % discard the labels
fprintf('Exported %d diagrams to %s\n', size(jobs, 1), fullfile(here, 'figs'));
end
